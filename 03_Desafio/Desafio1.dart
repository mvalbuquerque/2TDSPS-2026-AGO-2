O Briefing
Requisitos
Criar um programa em Dart registrando:

1. Nome do aluno (String)
2. Idade (int)
3. Curso (String)
4. Nota (double)
5. Está matriculado ou não (bool)
   Por fim, disparar todos os dados no console.

 */

void main() {
  // Variável do tipo STRING para armazenar o nome do aluno
  String nome = "Vinny Albuquerque";

  // Variável do tipo INT para armazenar a idade do aluno
  int idade = 44;

  // Variável do tipo STRING para armazenar o curso do aluno
  String curso = "Desenvolvimento de Software";

  // Variável do tipo DOUBLE para armazenar a nota do aluno
  double nota = 8.0;

  // Variável do tipo BOOL para armazenar se o aluno está matriculado ou não
  bool matriculado = true;

  //Exibindo as informações do aluno no output
  print("Nome do aluno: $nome");
  print("Idade do aluno: $idade");
  print("Curso do aluno: $curso");
  print("Nota do aluno: $nota");    
  print("Está matriculado? $matriculado");
}


