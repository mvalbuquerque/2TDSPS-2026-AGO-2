// Este programa demonstra como corrigir erros comuns de sintaxe em Dart.
// Erros frequentes: esquecer aspas, ponto-e-vírgula ou fechar parênteses.
void main() {
  // Sintaxe correta: print() com String entre aspas e ponto-e-vírgula no final.
  print('Aprendendo Dart');
  // Mais um exemplo de saída de texto sem erros de sintaxe.
  print('Primeiro modulo');
}
