// Este programa apresenta os tipos primitivos básicos do Dart:
// String (texto), int (inteiro), double (decimal) e bool (verdadeiro/falso).
void main() {
  // String: armazena sequências de caracteres (texto).
  String nome = 'Ana Martins';
  // int: armazena números inteiros (sem parte decimal).
  int idade = 24;
  // double: armazena números com ponto flutuante (com parte decimal).
  double altura = 1.68;
  // bool: armazena apenas dois valores possíveis — true ou false.
  bool estudante = true;

  // Interpolação de String: usa $ para inserir o valor de uma variável dentro do texto.
  print('Nome: $nome');
  print('Idade: $idade');
  print('Altura: $altura');
  print('Estudante: $estudante');
}
